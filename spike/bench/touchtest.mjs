import { chromium } from 'playwright';
import { ARGS, BASE } from './common.mjs';
const b = await chromium.launch({ headless: true, args: ARGS });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 }, hasTouch: true });
const p = await ctx.newPage(); const errs=[]; p.on('pageerror', e=>errs.push(String(e)));
await p.goto(`${BASE}/?renderer=canvas&bot=0&debug=0`); await p.waitForFunction(()=>window.__spike);
const cdp = await ctx.newCDPSession(p);
const t = (type, pts) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: pts.map((q,i)=>({x:q[0],y:q[1],id:i})) });
await p.evaluate(()=>window.__spike.god());
const gait = () => p.evaluate(()=>window.__spike.sim.pip.gait + ' moving=' + window.__spike.sim.pip.moving);
await t('touchStart', [[200,400]]); await t('touchMove', [[200+20,400]]); await p.waitForTimeout(200); console.log('tilt .29', await gait());
await t('touchMove', [[200+45,400]]); await p.waitForTimeout(200); console.log('tilt .64', await gait());
await t('touchMove', [[200+75,400]]); await p.waitForTimeout(200); console.log('tilt 1.0', await gait());
await t('touchEnd', []); 
const z0 = await p.evaluate(()=>window.__spike.cam.zoomTarget);
await t('touchStart', [[800,300],[1000,300]]); for (let i=1;i<=6;i++) await t('touchMove', [[800-i*20,300],[1000+i*20,300]]); await t('touchEnd', []);
await p.waitForTimeout(400); console.log('pinch zoom', z0, '->', await p.evaluate(()=>window.__spike.cam.zoomTarget));
await p.keyboard.press('Equal'); await p.keyboard.press('Equal'); console.log('after + +', await p.evaluate(()=>window.__spike.cam.zoomTarget));
await p.keyboard.press('KeyP'); console.log('proj', await p.evaluate(()=>window.__spike.scene.proj.name), p.url());
await p.mouse.wheel(0, 300); await p.waitForTimeout(100); console.log('wheel', await p.evaluate(()=>window.__spike.cam.zoomTarget), errs);
await b.close();
